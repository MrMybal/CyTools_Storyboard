"""Image generation operations: plans, generation on the persistent engine, kept pictures,
ComfyUI workflows, and the engine/model installation behind them."""
import json
import subprocess
import sys
from pathlib import Path

from cytools_core import CyToolError

from . import engines, imageengine, imagegen, imagemodels, model
from .paths import APP, ROOT, base_python

PLAN_KEYS = ('item', 'panel', 'views', 'character', 'prompt', 'references', 'format', 'extra', 'extras', 'label')


def register(runtime, open_project):
    engine = imageengine.ImageEngine(runtime)
    runtime.image_engine = engine

    def board_of(parameters):
        return open_project(parameters) if parameters.get('project') else None

    def plan_of(board, parameters):
        recipe = parameters.get('recipe', 'free')
        if board is None and recipe != 'free':
            raise CyToolError('InvalidParameters', f'The "{recipe}" recipe needs a project.')
        try:
            options = imagegen.options_for(board, parameters.get('options') or {})
            arguments = {k: parameters[k] for k in PLAN_KEYS if k in parameters}
            limit, token = imageengine.reference_rules(options)
            return options, imagegen.plan(board, recipe, options, limit, token, imageengine.control_available(options),
                                          **arguments)
        except (model.StoryboardError, KeyError) as exc:
            message = f'Missing parameter {exc}' if isinstance(exc, KeyError) else str(exc)
            raise CyToolError('InvalidParameters', message) from None

    def plan_images(context, parameters):
        options, requests = plan_of(board_of(parameters), parameters)
        return {'requests': requests, 'options': options}

    def generate_images(context, parameters):
        board = board_of(parameters)
        options, requests = plan_of(board, parameters)
        context.progress(0, currentStep='Starting the image engine')
        folder = context.path('outputs/pictures')
        try:
            pictures = engine.generate(context, requests, options, folder, board)
        except model.StoryboardError as exc:
            raise CyToolError('InvalidParameters', str(exc)) from None
        kept = []
        for picture in pictures:
            Path(picture['file'] + '.json').write_text(json.dumps(picture, indent=1, ensure_ascii=False), encoding='utf-8')
        if parameters.get('keep') and board is not None:
            board = open_project(parameters)     # the project may have changed while the pictures were rendered
            for picture in pictures:
                picture['asset'] = imagegen.keep(board, picture['file'], picture, picture.get('engine'),
                                                 attach=parameters.get('attach', True))
                kept.append(picture['asset'])
        if parameters.get('save_options') and board is not None:
            if not kept:
                board = open_project(parameters)     # never write back the state read before the pictures were rendered
            board.doc['settings']['imagegen'] = options
        if board is not None and (kept or parameters.get('save_options')):
            board.save()
        context.progress(100, currentStep='done')
        return {'pictures': pictures, 'kept': kept, 'folder': str(folder), 'engine': engine.status()['last'],
                'project': str(board.folder) if board is not None else ''}

    def keep_generated_image(context, parameters):
        board = open_project(parameters)
        picture = Path(parameters['file'])
        sidecar = Path(str(picture) + '.json')
        if not picture.is_file() or not sidecar.is_file():
            raise CyToolError('InvalidParameters', f'{picture} is not a picture generated by generate_images.')
        recipe = json.loads(sidecar.read_text(encoding='utf-8'))
        try:
            relative = imagegen.keep(board, picture, recipe, recipe.get('engine'), attach=parameters.get('attach', True))
        except model.StoryboardError as exc:
            raise CyToolError('InvalidParameters', str(exc)) from None
        board.save()
        return {'project': str(board.folder), 'asset': relative, 'target': recipe.get('target', {})}

    def export_image_workflows(context, parameters):
        from . import comfy_image_workflow
        board = board_of(parameters)
        options, requests = plan_of(board, parameters)
        target = Path(parameters['folder']) if parameters.get('folder') else \
            (board.folder / 'exports' / 'comfyui_images' if board is not None else context.path('outputs/comfyui_images'))
        try:
            result = comfy_image_workflow.export(requests, options, target, name=parameters.get('name', ''), board=board)
        except model.StoryboardError as exc:
            raise CyToolError('InvalidParameters', str(exc)) from None
        return dict(result, project=str(board.folder) if board is not None else '')

    def image_engine_status(context, parameters):
        return {'engine': engines.status(imageengine.ENGINE), 'models': imagemodels.status_all(),
                'loras': imageengine.lora_files(), 'loraFolder': str(imageengine.lora_folder()), **engine.status()}

    def unload_image_model(context, parameters):
        return engine.unload()

    def install_image_engine(context, parameters):
        log_path = context.path('logs/install-engine.log')
        command = [str(base_python()), str(APP / 'setup_engine.py'), imageengine.ENGINE] + \
            (['--cpu-only'] if parameters.get('cpu_only') else [])
        context.log('Running ' + ' '.join(command))
        flags = getattr(subprocess, 'CREATE_NO_WINDOW', 0) if sys.platform == 'win32' else 0
        engine.unload()
        with open(log_path, 'w', encoding='utf-8', errors='replace') as handle:
            process = subprocess.Popen(command, cwd=str(ROOT), stdout=handle, stderr=subprocess.STDOUT, creationflags=flags)
            try:
                while process.poll() is None:
                    try:
                        context.cancellation.sleep(1.0)
                    except CyToolError:
                        _terminate(process)
                        raise
                    try:
                        tail = log_path.read_text('utf-8', errors='replace').strip().splitlines()
                        context.progress(50, currentStep='Installing the image engine', statusMessage=(tail[-1] if tail else '')[:300])
                    except OSError:
                        pass
            finally:
                if process.poll() is None:
                    _terminate(process)
        if process.returncode != 0:
            tail = log_path.read_text('utf-8', errors='replace')[-4000:]
            raise CyToolError('InstallFailed', f'Engine installation failed (exit {process.returncode}); see {log_path}',
                              details={'log': tail}, recoverable=True)
        context.progress(100, currentStep='Installed')
        return {'engine': engines.status(imageengine.ENGINE), 'log': str(log_path)}

    def known(parameters):
        try:
            return imagemodels.get(parameters['model'])
        except KeyError:
            raise CyToolError('InvalidParameters', f'Unknown model "{parameters["model"]}" (see image_engine_status).') from None

    def install_image_model(context, parameters):
        known(parameters)

        def progress(done, size, name):
            context.progress(min(99.0, 100.0 * done / max(size, 1)), currentStep='Downloading', currentFile=name,
                             statusMessage=f'{done / 1e9:.2f} / {size / 1e9:.2f} GB')
        context.progress(0, currentStep='Checking files')
        result = imagemodels.install(parameters['model'], accept_license=bool(parameters.get('accept_license')),
                                     repair=bool(parameters.get('repair')), cancellation=context.cancellation,
                                     progress=progress, log=lambda m: context.log(m))
        context.progress(100, currentStep='Installed')
        return result

    def verify_image_model(context, parameters):
        known(parameters)
        context.progress(5, currentStep='Hashing files')
        result = imagemodels.verify(parameters['model'])
        context.progress(100, currentStep='Done')
        return result

    def remove_image_model(context, parameters):
        known(parameters)
        engine.unload()
        return imagemodels.remove(parameters['model'])

    for name, handler in list(locals().items()):
        if name in OPERATIONS:
            runtime.register(name, handler)
    return engine


OPERATIONS = ('plan_images', 'generate_images', 'keep_generated_image', 'export_image_workflows', 'image_engine_status',
              'unload_image_model', 'install_image_engine', 'install_image_model', 'verify_image_model',
              'remove_image_model')


def _terminate(process):
    try:
        import psutil
        parent = psutil.Process(process.pid)
        for child in parent.children(recursive=True):
            try:
                child.terminate()
            except psutil.NoSuchProcess:
                pass
        parent.terminate()
        psutil.wait_procs([parent], timeout=5)
        if process.poll() is None:
            process.kill()
    except Exception:
        process.kill()
